#!/bin/bash
# version.sh — single source of truth for the build identity of stream1090-turbo
#
# Produces a version string made of four parts, so any binary can be traced back
# to the exact source state it was built from:
#
#   <semver>.<build-num>+<git-sha>[.dirty].<source-fingerprint>
#   1.0.1.3+5a2b1c9.9f3a1c02be74
#
#   semver       from VERSION, changed by a human when the contract changes
#   build-num    git rev-list --count --first-parent HEAD, monotonic, automatic
#   git-sha      short commit id, plus .dirty when src/ VERSION patches/ changed
#   fingerprint  sha256 over the files that actually get compiled, reproducible
#
# Same source state -> same string -> same binary. That is what keeps the
# validation baseline (md5 f91f3d70...) meaningful.
#
# Usage:
#   tools/version.sh                 print the full version string
#   tools/version.sh --frozen        print "stream1090-turbo <semver>" only
#   tools/version.sh --number        print the monotonic build number
#   tools/version.sh --info          print BUILDINFO key=value lines
#   tools/version.sh --write         write BUILDINFO into the repository root
#   tools/version.sh --src DIR       fingerprint DIR instead of ./src (--upstream)
#   tools/version.sh --suffix S      append S before the fingerprint (--upstream)
#
# Environment:
#   STREAM1090_VERSION   if set, printed verbatim; all detection is skipped.
#                        Used when cross-building, so the target binary carries
#                        the identity of the host checkout that produced it.
set -e

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)

SRC="$ROOT/src"
MODE=version
SUFFIX=""

while [ $# -gt 0 ]; do
    case "$1" in
        --src)      SRC=$2; shift 2 ;;
        --src=*)    SRC=${1#*=}; shift ;;
        --suffix)   SUFFIX=$2; shift 2 ;;
        --suffix=*) SUFFIX=${1#*=}; shift ;;
        --number)   MODE=number; shift ;;
        --info)     MODE=info; shift ;;
        --write)    MODE=write; shift ;;
        --frozen)   MODE=frozen; shift ;;
        -h|--help)  sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *)          printf 'unknown option: %s\n' "$1" >&2; exit 2 ;;
    esac
done

if [ -n "${STREAM1090_VERSION:-}" ]; then
    case "$MODE" in
        number) printf '%s\n' "${STREAM1090_BUILD_NUM:-0}" ;;
        frozen) printf 'stream1090-turbo %s\n' "$(tr -d ' \n' < "$ROOT/VERSION" 2>/dev/null || echo 0.0.0)" ;;
        *)      printf '%s\n' "$STREAM1090_VERSION" ;;
    esac
    exit 0
fi

SEMVER=$(tr -d ' \n' < "$ROOT/VERSION" 2>/dev/null || true)
[ -n "$SEMVER" ] || SEMVER=0.0.0

have_git=0
[ -d "$ROOT/.git" ] && have_git=1

if [ "$have_git" = 1 ]; then
    NUM=$(git -C "$ROOT" rev-list --count --first-parent HEAD 2>/dev/null || echo 0)
    SHA=$(git -C "$ROOT" rev-parse --short=7 HEAD 2>/dev/null || echo unknown)
    DESC=$(git -C "$ROOT" describe --tags --always 2>/dev/null || echo "$SHA")
    # only the inputs that reach the compiler decide "dirty"
    if [ -n "$(git -C "$ROOT" status --porcelain -- src VERSION patches 2>/dev/null)" ]; then
        DIRTY=1
    else
        DIRTY=0
    fi
else
    NUM=0
    SHA=unknown
    DESC=unknown
    DIRTY=0
fi

# sha256 over every file that ends up in the object files; names included so a
# file split or rename changes the fingerprint too.
fingerprint() {
    local dir=$1 algo=sha256sum out=""
    command -v sha256sum >/dev/null 2>&1 || algo=md5sum
    command -v "$algo" >/dev/null 2>&1 || { echo 000000000000; return; }
    if [ -d "$dir" ]; then
        out=$(
            cd "$dir" &&
            find . -type f \( -name '*.hpp' -o -name '*.h' -o -name '*.cpp' -o -name '*.c' \) \
                -print0 2>/dev/null |
            LC_ALL=C sort -z |
            xargs -0 -r "$algo" 2>/dev/null |
            cut -d' ' -f1 |
            "$algo" | cut -c1-24
        )
    fi
    echo "${out:-000000000000}"
}

FP=$(fingerprint "$SRC")

dirty_tag=""
[ "$DIRTY" = 1 ] && dirty_tag=".dirty"
suffix_tag=""
[ -n "$SUFFIX" ] && suffix_tag=".${SUFFIX}"

VER="stream1090-turbo ${SEMVER}.${NUM}+${SHA}${suffix_tag}${dirty_tag}.${FP}"

case "$MODE" in
    version)
        printf '%s\n' "$VER"
        ;;
    frozen)
        printf 'stream1090-turbo %s\n' "$SEMVER"
        ;;
    number)
        printf '%s\n' "$NUM"
        ;;
    info)
        cat <<EOF
name=stream1090-turbo
semver=$SEMVER
build_num=$NUM
git_sha=$SHA
git_describe=$DESC
dirty=$DIRTY
source_fp=$FP
version=$VER
EOF
        ;;
    write)
        tmp="$ROOT/BUILDINFO.tmp"
        {
            cat <<EOF
# generated by tools/version.sh — do not edit, do not merge by hand
name=stream1090-turbo
semver=$SEMVER
build_num=$NUM
git_sha=$SHA
git_describe=$DESC
dirty=$DIRTY
source_fp=$FP
version=$VER
EOF
        } > "$tmp"
        mv "$tmp" "$ROOT/BUILDINFO"
        printf 'wrote %s\n' "$ROOT/BUILDINFO"
        ;;
esac
